#!/usr/bin/env python3
"""Regenerate macos/src/engine/nc_cache_census_*.inc: one line per container field
of TncSqliteDictionary and TncEngine, so a run can report entries per cache."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2] / "macos/src/engine"
def fields(path, start):
    text = (root / path).read_text(encoding="utf-8")
    a = text.index(start)
    body = text[a:text.index("\nimplementation", a)]
    return re.findall(r"^\s+(m_[a-z0-9_]+)\s*:\s*(?:TDictionary|TQueue|TList|TObjectList|TncStringMap|TncHashSet|TStringList)\b", body, re.M)
for name, source, start, cls in (("dictionary", "nc_dictionary_sqlite.pas", "TncSqliteDictionary = class", "TncSqliteDictionary"),
                                 ("engine", "nc_engine_intf.pas", "TncEngine = class", "TncEngine")):
    lines = ["{ Generated by scripts/gen_census.py }", f"procedure {cls}.cache_census(const sink: TncCensusSink);", "begin"]
    lines += [f"    if {f} <> nil then sink('{f}', {f}.Count);" for f in fields(source, start)]
    if cls == "TncEngine":
        lines.append("    if m_dictionary is TncSqliteDictionary then TncSqliteDictionary(m_dictionary).cache_census(sink);")
    lines.append("end;\n")
    (root / f"nc_cache_census_{name}.inc").write_text("\n".join(lines))
